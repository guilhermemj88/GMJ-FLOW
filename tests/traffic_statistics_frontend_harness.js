'use strict';
const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const js = fs.readFileSync(path.join(__dirname,'../frontend/threat-intelligence.js'),'utf8').split('// Traffic statistics: independent read-only UI; existing authenticated apiRequest.')[1];
const context = {};
vm.createContext(context);
vm.runInContext(js,context);
const ui = context.GMJTrafficStatistics;
assert.equal(ui.format(null),'—');
assert.equal(ui.format(0),'0');
assert.equal(ui.label('NO_BASELINE'),'Baseline em formação');
assert.equal(ui.label('HIGH_DIVERSITY'),'Alta diversidade');
assert.equal(ui.escape('<script>'), '&lt;script&gt;');
assert.ok(!js.includes('/mitigation'));
assert.ok(!js.includes('method:'));
assert.ok(js.includes('version !== revision'));
assert.ok(js.includes('connectNulls:false'));
console.log('9 frontend statistics checks passed');
